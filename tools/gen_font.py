#!/usr/bin/env python3
"""Render an 8x16 bitmap font header for the bdos console.

Usage: gen_font.py <font.otf|ttf> <out.h>

GNU Unifont is drawn on a 16-pixel grid with 8-pixel-wide ASCII glyphs,
so rendering it at 16px gives the original bitmaps back exactly.
Glyph 0xDB (the CP437 full block) is added by hand for the cursor.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H = 8, 16


def render(font, ch):
    img = Image.new("1", (W, H), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=1)
    rows = []
    for y in range(H):
        b = 0
        for x in range(W):
            if img.getpixel((x, y)):
                b |= 0x80 >> x
        rows.append(b)
    return rows


def main():
    src, out = sys.argv[1], sys.argv[2]
    font = ImageFont.truetype(src, 16)
    glyphs = [[0] * H for _ in range(256)]
    for c in range(0x21, 0x7F):
        glyphs[c] = render(font, chr(c))
    # the rest of code page 437: what DOS programs draw boxes and smileys with
    low = "\u263a\u263b\u2665\u2666\u2663\u2660\u2022\u25d8\u25cb\u25d9\u2642\u2640\u266a\u266b\u263c" \
          "\u25ba\u25c4\u2195\u203c\u00b6\u00a7\u25ac\u21a8\u2191\u2193\u2192\u2190\u221f\u2194\u25b2\u25bc"
    for i, ch in enumerate(low):
        glyphs[i + 1] = render(font, ch)
    glyphs[0x7F] = render(font, "\u2302")
    for c in range(0x80, 0x100):
        glyphs[c] = render(font, bytes([c]).decode("cp437"))
    # block elements, drawn exactly rather than trusting the font
    glyphs[0xDB] = [0xFF] * H
    glyphs[0xDC] = [0] * 8 + [0xFF] * 8
    glyphs[0xDD] = [0xF0] * H
    glyphs[0xDE] = [0x0F] * H
    glyphs[0xDF] = [0xFF] * 8 + [0] * 8
    glyphs[0xB0] = [0x88, 0x22] * 8
    glyphs[0xB1] = [0xAA, 0x55] * 8
    glyphs[0xB2] = [0xEE, 0xBB] * 8

    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_font.py from GNU Unifont. Do not edit. */\n")
        f.write("#pragma once\n#include <stdint.h>\n")
        f.write("static const uint8_t font8x16[256][16] = {\n")
        for c, rows in enumerate(glyphs):
            f.write("\t{" + ",".join("0x%02x" % r for r in rows) + "},")
            f.write(" /* %s */\n" % (repr(chr(c)) if 0x20 < c < 0x7F else "0x%02x" % c))
        f.write("};\n")


if __name__ == "__main__":
    main()
