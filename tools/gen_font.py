#!/usr/bin/env python3
"""Render an 8x16 bitmap font header for the bdos console.

Usage: gen_font.py <font.otf|ttf> <out.h>

GNU Unifont is drawn on a 16-pixel grid with 8-pixel-wide ASCII glyphs,
so rendering it at 16px gives the original bitmaps back exactly.
Glyph 0xDB (the CP437 full block) is added by hand for the cursor.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H = 8, 16


def render(font, ch):
    img = Image.new("1", (W, H), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=1)
    rows = []
    for y in range(H):
        b = 0
        for x in range(W):
            if img.getpixel((x, y)):
                b |= 0x80 >> x
        rows.append(b)
    return rows


def main():
    src, out = sys.argv[1], sys.argv[2]
    font = ImageFont.truetype(src, 16)
    glyphs = [[0] * H for _ in range(256)]
    for c in range(0x21, 0x7F):
        glyphs[c] = render(font, chr(c))
    glyphs[0xDB] = [0xFF] * H          # full block
    glyphs[0x5F + 0x80] = [0] * 14 + [0xFF, 0xFF]  # 0xDF: thick underline (cursor)

    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_font.py from GNU Unifont. Do not edit. */\n")
        f.write("#pragma once\n#include <stdint.h>\n")
        f.write("static const uint8_t font8x16[256][16] = {\n")
        for c, rows in enumerate(glyphs):
            f.write("\t{" + ",".join("0x%02x" % r for r in rows) + "},")
            f.write(" /* %s */\n" % (repr(chr(c)) if 0x20 < c < 0x7F else "0x%02x" % c))
        f.write("};\n")


if __name__ == "__main__":
    main()
